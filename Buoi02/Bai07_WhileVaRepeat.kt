package com.ute.baitap.Buoi2

fun main() {

    // Dung while khi so lan lap phu thuoc vao mot dieu kien
    var so: Int = 10

    while (so >= 1) {
        println(so)
        so--
    }


    // Dung repeat khi biet truoc so lan lap.
    repeat(5) {
        println("Truong Dai hoc Cong nghe Ky thuat TP.HCM - HCMUTE")
    }
}
